-- The service's final schema. Older migrations stay on `main` as history, so a database at
-- main's 006 can't be upgraded by this file: environments start from the baseline dump.

-- ---------------------------------------------------------------------------
-- Universe
-- ---------------------------------------------------------------------------

CREATE TABLE source (
  id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key  text NOT NULL UNIQUE,
  name text NOT NULL
);

CREATE TABLE organization (
  id         integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  slug       text NOT NULL UNIQUE,
  brand_name text NOT NULL,
  legal_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE asset (
  id             integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  slug           text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{1,64}$'),
  -- Not unique: tickers collide across issuers, so nothing may match on them.
  ticker         text NOT NULL,
  name           text NOT NULL,
  -- The provider's class name, word for word. The list is the provider's to change.
  asset_class    text NOT NULL,
  -- Our own grouping, which decides the catalog fields that normally apply.
  asset_type     text NOT NULL CHECK (asset_type IN
    ('tokenized_equity', 'tokenized_fund', 'tokenized_commodity', 'wrapped_crypto', 'native_crypto', 'defi_yield', 'stablecoin')),
  deactivated_at timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX asset_ticker_idx ON asset (ticker);

CREATE TABLE asset_alias (
  asset_id  integer NOT NULL REFERENCES asset (id),
  namespace text NOT NULL,
  value     text NOT NULL,
  PRIMARY KEY (namespace, value)
);
CREATE INDEX asset_alias_asset_idx ON asset_alias (asset_id);

CREATE TABLE asset_organization (
  asset_id        integer NOT NULL REFERENCES asset (id),
  organization_id integer NOT NULL REFERENCES organization (id),
  role            text NOT NULL,
  PRIMARY KEY (asset_id, organization_id, role)
);
CREATE INDEX asset_organization_organization_idx ON asset_organization (organization_id);

CREATE TABLE network (
  id                     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  key                    text NOT NULL UNIQUE,
  name                   text NOT NULL,
  -- EVM addresses compare case-insensitively; Solana addresses don't.
  address_case_sensitive boolean NOT NULL DEFAULT false
);

CREATE TABLE token (
  id             integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  asset_id       integer NOT NULL REFERENCES asset (id),
  network_id     integer NOT NULL REFERENCES network (id),
  address        text NOT NULL,
  issuance_type  text NOT NULL DEFAULT 'unknown' CHECK (issuance_type IN ('native', 'bridged', 'wrapper', 'unknown')),
  deactivated_at timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (network_id, address)
);
CREATE INDEX token_asset_idx ON token (asset_id);

CREATE FUNCTION normalize_chain_address() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT (SELECT address_case_sensitive FROM network WHERE id = NEW.network_id) THEN
    NEW.address := lower(NEW.address);
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER token_normalize_address BEFORE INSERT OR UPDATE OF address, network_id ON token
  FOR EACH ROW EXECUTE FUNCTION normalize_chain_address();

-- ---------------------------------------------------------------------------
-- Operations
-- ---------------------------------------------------------------------------

CREATE TABLE ingestion_run (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  source_id   smallint NOT NULL REFERENCES source (id),
  job         text NOT NULL CHECK (job IN ('universe', 'update')),
  started_at  timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  status      text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'succeeded', 'partial', 'failed', 'interrupted')),
  summary     jsonb NOT NULL DEFAULT '{}'
);

CREATE TABLE api_key (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  client_name  text NOT NULL,
  -- SHA-256 of the key. The key itself is never stored.
  key_hash     text NOT NULL UNIQUE CHECK (key_hash ~ '^[0-9a-f]{64}$'),
  key_prefix   text NOT NULL,
  expires_at   timestamptz,
  revoked_at   timestamptz,
  last_used_at timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Reference data
-- ---------------------------------------------------------------------------

CREATE TABLE field (
  id                     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  key                    text NOT NULL UNIQUE,
  category               text NOT NULL,
  label                  text NOT NULL,
  value_type             text NOT NULL CHECK (value_type IN
    ('text', 'long_text', 'url', 'date', 'boolean', 'integer', 'decimal', 'enum', 'list', 'identifier', 'address', 'organization')),
  level                  text NOT NULL CHECK (level IN ('asset', 'token', 'organization', 'network')),
  applicable_asset_types text[] NOT NULL CHECK (
    cardinality(applicable_asset_types) > 0 AND applicable_asset_types <@
    ARRAY['tokenized_equity', 'tokenized_fund', 'tokenized_commodity', 'wrapped_crypto', 'native_crypto', 'defi_yield', 'stablecoin']),
  requires_as_of         boolean NOT NULL DEFAULT false,
  -- Fields in the same group repeat together: one audit, one incident.
  record_group           text,
  sort_order             integer NOT NULL
);

CREATE TABLE field_value (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  field_id         integer NOT NULL REFERENCES field (id),
  asset_id         integer REFERENCES asset (id),
  token_id         integer REFERENCES token (id),
  organization_id  integer REFERENCES organization (id),
  network_id       integer REFERENCES network (id),
  subject_ref      text GENERATED ALWAYS AS (coalesce(
                     'asset:' || asset_id::text,
                     'token:' || token_id::text,
                     'organization:' || organization_id::text,
                     'network:' || network_id::text)) STORED,
  -- Identifies one repeating record, such as an audit. Empty for non-repeating fields.
  record_key       text NOT NULL DEFAULT '',
  -- A JSON null is not a value: a null from a provider produces no row at all.
  value            jsonb NOT NULL CHECK (jsonb_typeof(value) <> 'null'),
  raw_value        jsonb,
  as_of            date,
  source_id        smallint NOT NULL REFERENCES source (id),
  -- Empty for manual edits.
  ingestion_run_id bigint REFERENCES ingestion_run (id),
  missing_since    timestamptz,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  -- If set, the job won't overwrite or delete the row.
  locked_reason    text,
  CHECK (num_nonnulls(asset_id, token_id, organization_id, network_id) = 1),
  UNIQUE (field_id, subject_ref, record_key)
);
CREATE INDEX field_value_subject_idx ON field_value (subject_ref);

-- ---------------------------------------------------------------------------
-- Financials
-- ---------------------------------------------------------------------------

CREATE TABLE financial_measure (
  slug          text PRIMARY KEY,
  label         text NOT NULL,
  unit          text,
  measure_group text,
  kind          text CHECK (kind IN ('figure', 'term')),
  -- A new name from a provider starts false, so it's kept but not exposed until someone approves it.
  served        boolean NOT NULL DEFAULT false,
  definition    text,
  sort_order    integer
);

-- One row per current value, with no snapshot history. An empty token_id means the whole asset.
CREATE TABLE financial_current (
  asset_id         integer NOT NULL REFERENCES asset (id),
  token_id         integer REFERENCES token (id),
  metric           text NOT NULL REFERENCES financial_measure (slug),
  -- Empty for text, yes/no and list values, which live in raw.
  value            double precision,
  value_7d         double precision,
  value_30d        double precision,
  value_90d        double precision,
  raw              jsonb NOT NULL,
  as_of            date NOT NULL,
  ingestion_run_id bigint NOT NULL REFERENCES ingestion_run (id),
  missing_since    timestamptz,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE NULLS NOT DISTINCT (asset_id, token_id, metric)
);
CREATE INDEX financial_current_token_idx ON financial_current (token_id) WHERE token_id IS NOT NULL;

-- Daily history. A later load overwrites a day, because the source can restate it.
CREATE TABLE financial_timeseries (
  asset_id         integer NOT NULL REFERENCES asset (id),
  token_id         integer REFERENCES token (id),
  measure          text NOT NULL REFERENCES financial_measure (slug),
  day              date NOT NULL,
  value            double precision NOT NULL,
  ingestion_run_id bigint NOT NULL REFERENCES ingestion_run (id),
  UNIQUE NULLS NOT DISTINCT (asset_id, token_id, measure, day)
);
CREATE INDEX financial_timeseries_measure_idx ON financial_timeseries (measure, day);

-- ---------------------------------------------------------------------------
-- Views
-- ---------------------------------------------------------------------------

-- Every subject whose values count towards an asset.
CREATE VIEW asset_subject AS
SELECT a.id AS asset_id, 'asset' AS level, 'asset:' || a.id AS subject_ref FROM asset a
UNION ALL
SELECT t.asset_id, 'token', 'token:' || t.id FROM token t WHERE t.deactivated_at IS NULL
UNION ALL
SELECT DISTINCT t.asset_id, 'network', 'network:' || t.network_id FROM token t WHERE t.deactivated_at IS NULL
UNION ALL
SELECT ao.asset_id, 'organization', 'organization:' || ao.organization_id
FROM asset_organization ao WHERE ao.role = 'issuer';

-- A field has data if any of the asset's subjects has it, such as one of several tokens.
CREATE VIEW asset_field_status AS
SELECT
  a.id AS asset_id,
  f.id AS field_id,
  f.key AS field_key,
  f.category,
  CASE
    WHEN NOT a.asset_type = ANY (f.applicable_asset_types) THEN 'not_applicable'
    WHEN count(v.id) > 0 THEN 'with_data'
    ELSE 'no_data'
  END AS status
FROM asset a
CROSS JOIN field f
LEFT JOIN asset_subject s ON s.asset_id = a.id AND s.level = f.level
LEFT JOIN field_value v ON v.field_id = f.id AND v.subject_ref = s.subject_ref
GROUP BY a.id, a.asset_type, f.id, f.key, f.category, f.applicable_asset_types;

-- ---------------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------------

-- Default privileges give rwa_job every table, so these exceptions must be taken back as soon as
-- the tables exist. A bare database, such as CI's migration check, has no such roles.
DO $$
BEGIN
  IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'rwa_job') THEN
    REVOKE ALL ON api_key FROM rwa_job;
    REVOKE INSERT, UPDATE, DELETE ON field, source, schema_migration FROM rwa_job;
  END IF;
  IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'rwa_api') THEN
    GRANT UPDATE (last_used_at) ON api_key TO rwa_api;
  END IF;
END $$;
