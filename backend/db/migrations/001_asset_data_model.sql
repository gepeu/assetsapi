-- Every subject whose facts count towards an asset.
CREATE VIEW asset_subject AS
SELECT a.id AS asset_id, 'asset' AS level, 'asset:' || a.id AS subject_ref FROM asset a
UNION ALL
SELECT t.asset_id, 'token', 'token:' || t.id FROM token t
UNION ALL
SELECT DISTINCT t.asset_id, 'network', 'network:' || t.network_id FROM token t
UNION ALL
SELECT DISTINCT t.asset_id, 'contract', 'contract:' || tc.contract_id
FROM token t JOIN token_contract tc ON tc.token_id = t.id
UNION ALL
SELECT ao.asset_id, 'organization', 'organization:' || ao.organization_id
FROM asset_organization ao WHERE ao.role = 'issuer';

-- One status per asset and applicable field. A field counts as disclosed if any of the
-- asset's subjects discloses it, such as one of several tokens or one audit record.
CREATE VIEW asset_field_status AS
SELECT
  a.id AS asset_id,
  f.id AS field_id,
  f.key AS field_key,
  f.category,
  CASE
    WHEN bool_or(x.status = 'disclosed') THEN 'disclosed'
    WHEN bool_or(x.status = 'not_applicable') THEN 'not_applicable'
    WHEN bool_or(x.status = 'not_disclosed') THEN 'not_disclosed'
    WHEN bool_or(EXISTS (
      SELECT 1 FROM eligible_claim e
      WHERE e.field_id = f.id AND e.subject_ref = s.subject_ref AND e.is_subjective
    )) THEN 'attributed_only'
    ELSE 'never_checked'
  END AS status,
  coalesce(bool_or(x.has_conflict), false) AS has_conflict
FROM asset a
JOIN field f ON a.asset_type = ANY (f.applicable_asset_types)
LEFT JOIN asset_subject s ON s.asset_id = a.id AND s.level = f.level
LEFT JOIN fact x ON x.field_id = f.id AND x.subject_ref = s.subject_ref
GROUP BY a.id, f.id, f.key, f.category;

-- "25/60" = disclosed / applicable, per category. Sum the rows for an asset's overall figure.
CREATE VIEW asset_coverage AS
SELECT
  asset_id,
  category,
  count(*) FILTER (WHERE status = 'disclosed') AS disclosed,
  count(*) FILTER (WHERE status <> 'not_applicable') AS applicable,
  count(*) FILTER (WHERE status = 'not_disclosed') AS not_disclosed,
  count(*) FILTER (WHERE status = 'attributed_only') AS attributed_only,
  count(*) FILTER (WHERE status = 'never_checked') AS never_checked,
  count(*) FILTER (WHERE status = 'not_applicable') AS not_applicable,
  count(*) FILTER (WHERE has_conflict) AS conflicts
FROM asset_field_status
GROUP BY asset_id, category;
