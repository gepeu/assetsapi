-- Asset data model. Scope rule: no financial data or metrics. The field catalog is seed
-- data (src/db/catalog/fields.ts), so adding a field needs no migration.

-- ---------------------------------------------------------------------------
-- Reference records
-- ---------------------------------------------------------------------------

CREATE TABLE source (
  id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key  text NOT NULL UNIQUE,
  name text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('api', 'official_documents', 'chain', 'ai_researcher', 'manual_review'))
);

-- Conflict order. Lower rank wins. 'chain_first' covers token details and on-chain control.
CREATE TABLE source_priority (
  policy    text NOT NULL CHECK (policy IN ('chain_first', 'documents_first')),
  source_id smallint NOT NULL REFERENCES source (id),
  rank      smallint NOT NULL,
  PRIMARY KEY (policy, source_id),
  UNIQUE (policy, rank)
);

CREATE TABLE organization (
  id         integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  slug       text NOT NULL UNIQUE,
  brand_name text NOT NULL,   -- OnRe
  legal_name text,            -- On Re SAC Ltd.
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE asset (
  id            integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  slug          text NOT NULL UNIQUE,
  ticker        text NOT NULL UNIQUE,
  name          text NOT NULL,
  -- Our own label, shown in the UI. Sources' labels are claims on classification.asset_class.
  asset_class   text NOT NULL CHECK (asset_class IN
    ('equity', 'treasuries', 'private_credit', 'reinsurance', 'commodities', 'cryptocurrency', 'onchain_yield')),
  -- Our own grouping, which decides the catalog fields that normally apply to this asset.
  asset_type    text NOT NULL CHECK (asset_type IN
    ('tokenized_equity', 'tokenized_fund', 'tokenized_commodity', 'wrapped_crypto', 'native_crypto', 'defi_yield')),
  -- As listed in docs/token_universe.md: unverified, and never a Fact.
  listed_issuer text,
  review_note   text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- External identifiers: maple-usdc = syrupUSDC, tether-gold = XAUT, RWA.xyz IDs and so on.
CREATE TABLE asset_alias (
  asset_id   integer NOT NULL REFERENCES asset (id),
  namespace  text NOT NULL,
  value      text NOT NULL,
  verified   boolean NOT NULL DEFAULT false,
  PRIMARY KEY (namespace, value)
);
CREATE INDEX asset_alias_asset_idx ON asset_alias (asset_id);

CREATE TABLE asset_organization (
  asset_id        integer NOT NULL REFERENCES asset (id),
  organization_id integer NOT NULL REFERENCES organization (id),
  role            text NOT NULL,
  PRIMARY KEY (asset_id, organization_id, role)
);

CREATE TABLE network (
  id                     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  key                    text NOT NULL UNIQUE,
  name                   text NOT NULL,
  -- EVM addresses compare case-insensitively; Solana addresses don't.
  address_case_sensitive boolean NOT NULL DEFAULT false
);

CREATE TABLE token (
  id            integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  asset_id      integer NOT NULL REFERENCES asset (id),
  network_id    integer NOT NULL REFERENCES network (id),
  address       text NOT NULL,
  symbol        text,
  issuance_type text NOT NULL DEFAULT 'unknown' CHECK (issuance_type IN ('native', 'bridged', 'wrapper', 'unknown')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (network_id, address)
);
CREATE INDEX token_asset_idx ON token (asset_id);

CREATE TABLE contract (
  id         integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  network_id integer NOT NULL REFERENCES network (id),
  address    text NOT NULL,
  label      text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (network_id, address)
);

-- Many to many, because one program can serve many tokens.
CREATE TABLE token_contract (
  token_id    integer NOT NULL REFERENCES token (id),
  contract_id integer NOT NULL REFERENCES contract (id),
  role        text NOT NULL DEFAULT 'token',
  PRIMARY KEY (token_id, contract_id, role)
);

CREATE FUNCTION normalize_chain_address() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT (SELECT address_case_sensitive FROM network WHERE id = NEW.network_id) THEN
    NEW.address := lower(NEW.address);
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER token_normalize_address BEFORE INSERT OR UPDATE OF address, network_id ON token
  FOR EACH ROW EXECUTE FUNCTION normalize_chain_address();
CREATE TRIGGER contract_normalize_address BEFORE INSERT OR UPDATE OF address, network_id ON contract
  FOR EACH ROW EXECUTE FUNCTION normalize_chain_address();

-- ---------------------------------------------------------------------------
-- Documents
-- ---------------------------------------------------------------------------

CREATE TABLE document (
  id              integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  url             text NOT NULL UNIQUE,
  title           text,
  category        text NOT NULL DEFAULT 'other' CHECK (category IN
    ('website', 'docs', 'legal', 'terms', 'prospectus', 'fact_sheet', 'attestation', 'audit', 'transparency', 'guide', 'other')),
  last_checked_at timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now()
);

-- One row per fetch attempt, so a failed fetch is still recorded. Storage keys are relative,
-- never absolute paths, so moving to Railway means copying objects with no database rewrite.
CREATE TABLE stored_file (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  document_id    integer NOT NULL REFERENCES document (id),
  storage_key    text,
  sha256         text CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  size_bytes     bigint,
  content_type   text,
  retrieved_at   timestamptz NOT NULL DEFAULT now(),
  http_status    integer,
  fetch_error    text,
  final_url      text,
  redirect_chain jsonb NOT NULL DEFAULT '[]',
  is_empty_shell boolean NOT NULL DEFAULT false,
  CHECK (storage_key IS NULL OR (sha256 IS NOT NULL AND size_bytes IS NOT NULL)),
  CHECK (storage_key IS NOT NULL OR fetch_error IS NOT NULL),
  CHECK (storage_key IS NULL OR storage_key !~ '^(/|[A-Za-z]:)')
);
CREATE INDEX stored_file_document_idx ON stored_file (document_id, retrieved_at DESC);

CREATE TABLE asset_document (
  asset_id    integer NOT NULL REFERENCES asset (id),
  document_id integer NOT NULL REFERENCES document (id),
  -- Curated by us. Never inherited from a source.
  is_official boolean NOT NULL DEFAULT false,
  provenance  text NOT NULL,
  source      text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (asset_id, document_id)
);
CREATE INDEX asset_document_document_idx ON asset_document (document_id);

-- ---------------------------------------------------------------------------
-- Field catalog
-- ---------------------------------------------------------------------------

CREATE TABLE field (
  id                     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  key                    text NOT NULL UNIQUE,
  category               text NOT NULL,
  label                  text NOT NULL,
  value_type             text NOT NULL CHECK (value_type IN
    ('text', 'long_text', 'url', 'date', 'boolean', 'integer', 'decimal', 'enum', 'list', 'identifier', 'address', 'organization')),
  level                  text NOT NULL CHECK (level IN ('asset', 'token', 'organization', 'network', 'contract')),
  applicable_asset_types text[] NOT NULL CHECK (
    cardinality(applicable_asset_types) > 0 AND applicable_asset_types <@
    ARRAY['tokenized_equity', 'tokenized_fund', 'tokenized_commodity', 'wrapped_crypto', 'native_crypto', 'defi_yield']),
  conflict_policy        text NOT NULL CHECK (conflict_policy IN ('chain_first', 'documents_first')),
  requires_as_of         boolean NOT NULL DEFAULT false,
  -- Fields in the same group repeat together: one audit, one incident, one control row.
  record_group           text,
  sort_order             integer NOT NULL
);

-- Words that may only ever appear as attributed Claims, never as Facts.
CREATE TABLE subjective_term (
  pattern text PRIMARY KEY,
  note    text
);

-- ---------------------------------------------------------------------------
-- Ingestion
-- ---------------------------------------------------------------------------

CREATE TABLE ingestion_run (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  source_id   smallint NOT NULL REFERENCES source (id),
  started_at  timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  status      text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'succeeded', 'partial', 'failed')),
  parameters  jsonb NOT NULL DEFAULT '{}',
  summary     jsonb NOT NULL DEFAULT '{}'
);

-- Pointers to raw API responses, kept for audit only. They contain financial data, so they
-- are never mapped to fields or exposed.
CREATE TABLE raw_response (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ingestion_run_id bigint NOT NULL REFERENCES ingestion_run (id),
  request_path     text NOT NULL,
  storage_key      text NOT NULL CHECK (storage_key !~ '^(/|[A-Za-z]:)'),
  sha256           text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  http_status      integer,
  retrieved_at     timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Claims: who said what. Append-only.
-- ---------------------------------------------------------------------------

CREATE TABLE claim (
  id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  field_id          integer NOT NULL REFERENCES field (id),
  asset_id          integer REFERENCES asset (id),
  token_id          integer REFERENCES token (id),
  organization_id   integer REFERENCES organization (id),
  network_id        integer REFERENCES network (id),
  contract_id       integer REFERENCES contract (id),
  subject_ref       text GENERATED ALWAYS AS (coalesce(
                      'asset:' || asset_id::text,
                      'token:' || token_id::text,
                      'organization:' || organization_id::text,
                      'network:' || network_id::text,
                      'contract:' || contract_id::text)) STORED,
  -- Identifies one repeating record, such as an audit. Empty for non-repeating fields.
  record_key        text NOT NULL DEFAULT '',
  source_id         smallint NOT NULL REFERENCES source (id),
  ingestion_run_id  bigint NOT NULL REFERENCES ingestion_run (id),
  -- 'never checked' is not stored: it means no claim row exists.
  status            text NOT NULL CHECK (status IN ('disclosed', 'not_disclosed', 'not_applicable')),
  raw_value         jsonb,
  normalized_value  jsonb,
  note              text,
  as_of             date,
  observed_at       timestamptz NOT NULL DEFAULT now(),
  extraction_method text NOT NULL CHECK (extraction_method IN ('api', 'document_parse', 'chain_read', 'ai_extraction', 'manual')),
  withdrawn_at      timestamptz,
  withdrawn_reason  text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(asset_id, token_id, organization_id, network_id, contract_id) = 1),
  -- A JSON null is not a value: a null from an API must produce no claim at all.
  CHECK ((status = 'disclosed') = (normalized_value IS NOT NULL AND jsonb_typeof(normalized_value) <> 'null')),
  CHECK ((withdrawn_at IS NULL) = (withdrawn_reason IS NULL))
);
CREATE INDEX claim_lookup_idx ON claim (field_id, subject_ref, record_key);
CREATE INDEX claim_run_idx ON claim (ingestion_run_id);

CREATE FUNCTION claim_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  f field;
  subject_level text;
  run_source smallint;
  value jsonb := NEW.normalized_value;
BEGIN
  SELECT * INTO f FROM field WHERE id = NEW.field_id;

  subject_level := split_part(NEW.subject_ref, ':', 1);
  IF subject_level <> f.level THEN
    RAISE EXCEPTION 'field % belongs to subject level %, not %', f.key, f.level, subject_level;
  END IF;

  IF (f.record_group IS NULL) <> (NEW.record_key = '') THEN
    RAISE EXCEPTION 'field %: record_key is required only and always for repeating fields', f.key;
  END IF;

  SELECT source_id INTO run_source FROM ingestion_run WHERE id = NEW.ingestion_run_id;
  IF run_source <> NEW.source_id THEN
    RAISE EXCEPTION 'claim source does not match its ingestion run';
  END IF;

  IF NEW.status = 'disclosed' THEN
    IF f.requires_as_of AND NEW.as_of IS NULL THEN
      RAISE EXCEPTION 'field % changes quickly and needs an as-of date', f.key;
    END IF;

    IF f.value_type = 'boolean' AND jsonb_typeof(value) <> 'boolean'
       OR f.value_type IN ('integer', 'decimal') AND jsonb_typeof(value) <> 'number'
       OR f.value_type = 'list' AND jsonb_typeof(value) <> 'array'
       OR f.value_type IN ('text', 'long_text', 'url', 'date', 'enum', 'identifier', 'address')
          AND jsonb_typeof(value) <> 'string' THEN
      RAISE EXCEPTION 'field % expects a % value', f.key, f.value_type;
    END IF;

    -- Organization values point at a record, so spelling differences aren't false conflicts.
    IF f.value_type = 'organization' AND NOT EXISTS (
      SELECT 1 FROM organization WHERE id = (value ->> 'organization_id')::integer
    ) THEN
      RAISE EXCEPTION 'field % expects {"organization_id": <existing id>}', f.key;
    END IF;
  END IF;

  RETURN NEW;
END $$;

-- AFTER, because stored generated columns such as subject_ref aren't computed yet in BEFORE.
CREATE TRIGGER claim_validate AFTER INSERT ON claim
  FOR EACH ROW EXECUTE FUNCTION claim_validate();

-- The only permitted change is withdrawing a claim once. The record itself stays.
CREATE FUNCTION claim_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF OLD.withdrawn_at IS NULL AND NEW.withdrawn_at IS NOT NULL
       AND (to_jsonb(NEW) - 'withdrawn_at' - 'withdrawn_reason' - 'subject_ref') =
           (to_jsonb(OLD) - 'withdrawn_at' - 'withdrawn_reason' - 'subject_ref') THEN
      RETURN NEW;
    END IF;
    RAISE EXCEPTION 'claims are append-only: add a new claim or withdraw this one';
  END IF;
  RAISE EXCEPTION 'claims are append-only: withdraw instead of deleting';
END $$;

CREATE TRIGGER claim_no_change BEFORE UPDATE OR DELETE ON claim
  FOR EACH ROW EXECUTE FUNCTION claim_append_only();
CREATE TRIGGER claim_no_truncate BEFORE TRUNCATE ON claim
  FOR EACH STATEMENT EXECUTE FUNCTION claim_append_only();

CREATE TABLE claim_citation (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  claim_id       bigint NOT NULL REFERENCES claim (id),
  document_id    integer NOT NULL REFERENCES document (id),
  stored_file_id bigint REFERENCES stored_file (id),
  quote          text NOT NULL CHECK (length(btrim(quote)) > 0),
  locator        text,
  -- Set only once the quote has been found in the stored file.
  verified_at    timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CHECK (verified_at IS NULL OR stored_file_id IS NOT NULL)
);
CREATE INDEX claim_citation_claim_idx ON claim_citation (claim_id);

CREATE FUNCTION citation_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND (to_jsonb(NEW) - 'verified_at' - 'stored_file_id') =
                          (to_jsonb(OLD) - 'verified_at' - 'stored_file_id') THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'citations are append-only, apart from recording verification';
END $$;

CREATE TRIGGER citation_no_change BEFORE UPDATE OR DELETE ON claim_citation
  FOR EACH ROW EXECUTE FUNCTION citation_append_only();

-- Pins one claim as the Fact for its field, subject and record, whatever the conflict order says.
CREATE TABLE fact_override (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  claim_id     bigint NOT NULL REFERENCES claim (id),
  field_id     integer NOT NULL,
  subject_ref  text NOT NULL,
  record_key   text NOT NULL,
  reason       text NOT NULL CHECK (length(btrim(reason)) > 0),
  created_by   text NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  cleared_at   timestamptz
);
CREATE UNIQUE INDEX fact_override_one_active ON fact_override (field_id, subject_ref, record_key)
  WHERE cleared_at IS NULL;

CREATE FUNCTION fact_override_fill() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  SELECT field_id, subject_ref, record_key INTO NEW.field_id, NEW.subject_ref, NEW.record_key
  FROM claim WHERE id = NEW.claim_id;
  RETURN NEW;
END $$;

CREATE TRIGGER fact_override_fill BEFORE INSERT ON fact_override
  FOR EACH ROW EXECUTE FUNCTION fact_override_fill();

-- ---------------------------------------------------------------------------
-- Facts: what we believe. A view, so a Fact can never disagree with its claims.
-- ---------------------------------------------------------------------------

-- Claims that count: not withdrawn, and for AI claims, at least one verified citation.
-- An AI claim verified against an official document ranks as that official document.
CREATE VIEW eligible_claim AS
SELECT
  c.*,
  CASE
    WHEN s.kind = 'ai_researcher' AND EXISTS (
      SELECT 1
      FROM claim_citation cc
      JOIN asset_document ad ON ad.document_id = cc.document_id AND ad.is_official
      WHERE cc.claim_id = c.id AND cc.verified_at IS NOT NULL
    ) THEN (
      SELECT sp.rank
      FROM source_priority sp
      JOIN source os ON os.id = sp.source_id
      WHERE sp.policy = f.conflict_policy AND os.kind = 'official_documents'
    )
    ELSE p.rank
  END AS effective_rank,
  o.id AS override_id,
  o.reason AS override_reason,
  EXISTS (
    SELECT 1 FROM subjective_term t WHERE c.normalized_value::text ~* t.pattern
  ) AS is_subjective
FROM claim c
JOIN field f ON f.id = c.field_id
JOIN source s ON s.id = c.source_id
JOIN source_priority p ON p.policy = f.conflict_policy AND p.source_id = c.source_id
LEFT JOIN fact_override o ON o.claim_id = c.id AND o.cleared_at IS NULL
WHERE c.withdrawn_at IS NULL
  AND (s.kind <> 'ai_researcher' OR EXISTS (
    SELECT 1 FROM claim_citation cc WHERE cc.claim_id = c.id AND cc.verified_at IS NOT NULL
  ));

-- One current claim per source: a newer observation replaces the same source's older one.
CREATE VIEW current_claim AS
SELECT DISTINCT ON (field_id, subject_ref, record_key, source_id) *
FROM eligible_claim
WHERE NOT is_subjective
ORDER BY field_id, subject_ref, record_key, source_id,
         (override_id IS NOT NULL) DESC, observed_at DESC, id DESC;

CREATE VIEW fact AS
WITH ranked AS (
  SELECT
    cc.*,
    row_number() OVER (
      PARTITION BY field_id, subject_ref, record_key
      ORDER BY (override_id IS NOT NULL) DESC,
               -- "Couldn't find it" never beats a source that states a value.
               (status = 'not_disclosed'),
               effective_rank, observed_at DESC, id DESC
    ) AS position
  FROM current_claim cc
),
disagreement AS (
  -- Disclosed values and "not applicable" can contradict. "Not disclosed" cannot.
  SELECT
    field_id, subject_ref, record_key,
    count(DISTINCT status || coalesce(normalized_value::text, '')) > 1 AS has_conflict,
    array_agg(id ORDER BY id) AS claim_ids
  FROM current_claim
  WHERE status <> 'not_disclosed'
  GROUP BY field_id, subject_ref, record_key
)
SELECT
  r.field_id, r.subject_ref, r.asset_id, r.token_id, r.organization_id, r.network_id, r.contract_id,
  r.record_key,
  r.id AS claim_id,
  r.source_id,
  r.status,
  r.raw_value,
  r.normalized_value,
  r.as_of,
  r.observed_at,
  coalesce(d.has_conflict, false) AS has_conflict,
  CASE WHEN d.has_conflict THEN d.claim_ids ELSE '{}'::bigint[] END AS conflicting_claim_ids,
  r.override_id IS NOT NULL AS is_override,
  r.override_reason
FROM ranked r
LEFT JOIN disagreement d USING (field_id, subject_ref, record_key)
WHERE r.position = 1;

